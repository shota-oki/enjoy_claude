/** メッセージを取得し、{key} を値で置き換える */
export function msg(
  id: MessageId,
  params: Record<string, string | number> = {},
): string {
  return MESSAGES[id].replace(/\{(\w+)\}/g, (whole, key: string) =>
    key in params ? String(params[key]) : whole,
  );
}
